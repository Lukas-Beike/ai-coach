class ActivityKindParityTests(unittest.TestCase):
    def test_every_recorded_input_keeps_its_legacy_family(self) -> None:
        for activity, expected in LEGACY_PARITY_TABLE:
            with self.subTest(activity=activity):
                self.assertEqual(expected, activity_kind(activity))

    def test_table_exercises_every_legacy_family(self) -> None:
        self.assertEqual(
            {"cycling", "running", "swimming", "strength", "other"},
            {family for _, family in LEGACY_PARITY_TABLE},
        )


if __name__ == "__main__":
    unittest.main()
